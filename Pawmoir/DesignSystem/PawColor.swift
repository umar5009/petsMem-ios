import SwiftUI

/// Asset-catalog colors. Every screen should use these so Dark Mode stays warm.
enum PawColor {
    static let background = Color("Background")
    static let surface = Color("Surface")
    static let surfaceElevated = Color("SurfaceElevated")
    static let primary = Color("Primary")
    static let primaryPressed = Color("PrimaryPressed")
    static let secondary = Color("Secondary")
    static let textPrimary = Color("TextPrimary")
    static let textSecondary = Color("TextSecondary")
    static let textTertiary = Color("TextTertiary")
    static let accent = Color("Highlight")
    static let destructive = Color("Destructive")
    static let separator = Color("Separator")
    static let coralSoft = Color("CoralSoft")
    static let sageSoft = Color("SageSoft")
    static let onPrimary = Color("OnPrimary")
}
